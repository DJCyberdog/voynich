"""Explicit local source-only update with verified rollback and no state migration."""
import hashlib
import json
import os
import re
import stat
import tempfile
import zipfile
from pathlib import Path
from vrs_portable import local, need, load, save, digest, exclusive, worker_stopped, HEX

PREFIX='Voynich Research Studio/'
MANIFEST='portable_sources.json'
JOURNAL='workspace/source-update/journal.json'
CAP=64*1024**2
FILE_CAP=8*1024**2
BLOB=re.compile('[a-f0-9]{40}')
NAME=re.compile(r'(?:[A-Za-z0-9_.-]+\.(?:py|pyw|md|txt|cmd|bat)|module_assets/[A-Za-z0-9_.-]+\.(?:py|md|json|csv))')


def blob(data):return hashlib.sha1(b'blob '+str(len(data)).encode()+b'\0'+data).hexdigest()


def manifest(data):
    def pairs(items):
        d=dict(items);need(len(d)==len(items),'Duplicate source manifest key');return d
    need(len(data)<=2*1024**2,'Manifest quota');v=json.loads(data,object_pairs_hook=pairs)
    need(type(v) is dict and set(v)=={'schema','files'} and v['schema']==1 and type(v['files']) is dict and 0<len(v['files'])<=500,'Invalid source manifest')
    m=v['files'];need(len({n.casefold() for n in m})==len(m),'Case-colliding source paths')
    need(all(NAME.fullmatch(n) and not n.startswith('.') and isinstance(h,str) and BLOB.fullmatch(h) for n,h in m.items()),'Unmanaged source path or hash')
    return m


def read_bundle(path,approved):
    path=Path(path);need(path.is_file() and not path.is_symlink() and path.stat().st_size<=CAP and isinstance(approved,str) and HEX.fullmatch(approved),'Invalid source package approval')
    # Read the approved bytes once, so the archive cannot be swapped after verification.
    data=path.read_bytes();need(len(data)<=CAP and hashlib.sha256(data).hexdigest()==approved,'Source package approval mismatch')
    import io
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        files={};seen=set();total=0
        need(1<len(z.infolist())<=501,'Source archive cardinality')
        for i in z.infolist():
            need(i.orig_filename==i.filename and i.filename.startswith(PREFIX),'Unexpected or normalized source archive root');n=i.filename[len(PREFIX):]
            need((n==MANIFEST or NAME.fullmatch(n)) and n.casefold() not in seen and not i.is_dir() and not i.flag_bits&1 and not i.external_attr&1024 and stat.S_IFMT(i.external_attr>>16) in (0,stat.S_IFREG),'Unsafe source archive member')
            seen.add(n.casefold());total+=i.file_size;need(total<=CAP and i.file_size<=FILE_CAP and i.file_size<=max(1024**2,i.compress_size*500),'Source archive quota');files[n]=z.read(i)
    need(MANIFEST in files,'Source manifest missing');m=manifest(files[MANIFEST]);need(set(files)==set(m)|{MANIFEST} and all(blob(files[n])==h for n,h in m.items()),'Source archive does not match manifest');return files,m


def installed(root):
    p=local(root,MANIFEST);data=p.read_bytes();m=manifest(data);files={MANIFEST:data};total=len(data)
    for n,h in m.items():
        p=local(root,n);need(p.is_file() and p.stat().st_size<=FILE_CAP,'Installed source missing or oversized');b=p.read_bytes();total+=len(b);need(total<=CAP and blob(b)==h,'Installed source modified');files[n]=b
    return files,m


def write(path,data):
    path.parent.mkdir(parents=True,exist_ok=True);fd,tmp=tempfile.mkstemp(prefix='.source-',dir=path.parent)
    try:
        with os.fdopen(fd,'wb') as f:f.write(data);f.flush();os.fsync(f.fileno())
        os.replace(tmp,path)
    finally:Path(tmp).unlink(missing_ok=True)


def pending(root):return local(root,JOURNAL).exists()


def invalidate_bytecode(root):
    # These are reserved generated bytecode locations, not research/user data.
    import shutil
    for n in ('cache/pyc','__pycache__','module_assets/__pycache__'):
        p=local(root,n)
        if p.exists():need(p.is_dir(),'Unexpected bytecode cache');shutil.rmtree(p)



def maintenance(root):
    session=local(root,'workspace/vrs101/session.json');need(not session.exists() or worker_stopped(root),'Stop managed worker before source maintenance')


def rollback(root):
    j=load(local(root,JOURNAL));need(set(j)=={'schema','changes','backup'} and j['schema']==1 and j['backup']=='workspace/source-update/backup' and type(j['changes']) is dict and 0<len(j['changes'])<=1001 and MANIFEST in j['changes'],'Invalid source recovery journal')
    changes=j['changes'];need(len({n.casefold() for n in changes})==len(changes),'Recovery case collision')
    # Verify every target and backup before modifying anything. Refuse external edits.
    restore={};total=0
    for n,v in changes.items():
        need((n==MANIFEST or NAME.fullmatch(n) and not n.startswith('.')) and type(v) is dict and set(v)=={'old','new'} and all(x is None or isinstance(x,str) and BLOB.fullmatch(x) for x in v.values()) and v['old']!=v['new'],'Invalid recovery record')
        p=local(root,n);cur=None
        if p.exists():need(p.is_file() and p.stat().st_size<=FILE_CAP,'Unsafe recovery target');cur=blob(p.read_bytes())
        need(cur in (v['old'],v['new']),'Recovery target externally modified')
        if v['old'] is not None:
            b=local(root,j['backup']+'/'+n);need(b.is_file() and b.stat().st_size<=FILE_CAP,'Recovery backup missing');data=b.read_bytes();total+=len(data);need(total<=CAP and blob(data)==v['old'],'Recovery backup mismatch');restore[n]=data
    for n in sorted(changes,key=lambda n:(n==MANIFEST,n)):
        p=local(root,n)
        if n in restore:write(p,restore[n])
        else:p.unlink(missing_ok=True)
    installed(root);invalidate_bytecode(root);local(root,JOURNAL).unlink()
    # Backup intentionally retained until next explicitly approved update, for manual audit.


def update(root,bundle,approved):
    root=Path(root).resolve(strict=True)
    with exclusive(root):
        maintenance(root);need(not pending(root),'Source recovery required');old,om=installed(root);new,nm=read_bundle(bundle,approved)
        # A dependency or launcher change needs an explicit new environment/package.
        stable=lambda n:n in ('vrs_portable.py','vrs_source_update.py','vrs_portable_logs.py') or n.endswith(('.bat','.cmd')) or n.startswith('requirements') and n.endswith('.txt')
        need(all(old.get(n)==new.get(n) for n in set(old)|set(new) if stable(n)),'Recovery/launcher/dependency change requires full package migration')
        names=set(old)|set(new);need(len({n.casefold() for n in names})==len(names),'Cross-version case collision')
        changed={n:{'old':blob(old[n]) if n in old else None,'new':blob(new[n]) if n in new else None} for n in names if old.get(n)!=new.get(n)}
        if not changed:return {'status':'UNCHANGED','files':0}
        need(MANIFEST in changed and len(changed)<=1001,'Manifest change or update cardinality')
        for n in changed:
            if n not in old:need(not local(root,n).exists(),'Unmanaged file collision')
        import shutil
        backup=local(root,'workspace/source-update/backup')
        if backup.exists():shutil.rmtree(backup)
        backup.mkdir(parents=True)
        for n in changed:
            if n in old:write(local(root,'workspace/source-update/backup/'+n),old[n])
        save(local(root,JOURNAL),{'schema':1,'changes':changed,'backup':'workspace/source-update/backup'})
        try:
            for n in sorted(changed,key=lambda n:(n==MANIFEST,n)):
                p=local(root,n)
                if n in new:write(p,new[n])
                else:p.unlink()
            _,verified=installed(root);need(verified==nm,'Updated manifest mismatch');invalidate_bytecode(root);local(root,JOURNAL).unlink()
        except BaseException:
            rollback(root);raise
        return {'status':'UPDATED','files':len(changed)-1,'sha256':approved}


def recover(root):
    root=Path(root).resolve(strict=True)
    with exclusive(root,allow_source_recovery=True):maintenance(root);need(pending(root),'No interrupted source update');rollback(root)
    return {'status':'ROLLED_BACK'}
